// CPU-vs-CPU balance runner (ROADMAP.md R2/R4). Run: npm run balance
// Plays every pair of jobs both ways at Senior level and writes design/balance-report.md.
import { writeFileSync } from "node:fs";
import { describe, it } from "vitest";
import { playMatch } from "../src/ai/runner";
import { KITS } from "../src/sim/data/kits.gen";

const RUN = process.env.BALANCE === "1";
const LEVEL = Number(process.env.LEVEL ?? 4), GAMES = Number(process.env.GAMES ?? 2);

describe.skipIf(!RUN)("balance", () => {
  it("plays every matchup", () => {
    const n = KITS.length, wins = new Array(n).fill(0), games = new Array(n).fill(0);
    const pair: number[][] = Array.from({ length: n }, () => new Array(n).fill(0));
    let frames = 0, rounds = 0, timeouts = 0;
    for (let a = 0; a < n; a++) for (let b = a + 1; b < n; b++) for (let g = 0; g < GAMES; g++) {
      const swap = g % 2 === 1, jobs: [number, number] = swap ? [b, a] : [a, b];
      const r = playMatch({ jobs, arena: g % 2, seed: 1000 + a * 97 + b * 13 + g }, [LEVEL, LEVEL]);
      frames += r.frames; rounds += r.rounds;
      if (r.winner === 2 || r.winner < 0) { timeouts++; continue; }
      const w = jobs[r.winner], l = jobs[1 - r.winner];
      wins[w]++; games[w]++; games[l]++; pair[w][l]++;
    }
    const rows = KITS.map((k, j) => ({ name: k.name, wr: games[j] ? wins[j] / games[j] : 0, games: games[j] })).sort((x, y) => y.wr - x.wr);
    const out = [
      `# Balance report (CPU vs CPU, level ${LEVEL}, ${GAMES} games per pair)`,
      "",
      `Generated by \`npm run balance\`. Average round: ${(frames / rounds / 60).toFixed(1)} s. Undecided matches: ${timeouts}.`,
      "Target: every job between 45 % and 55 %.",
      "",
      "| Job | Win rate | Games |",
      "|---|---|---|",
      ...rows.map((r) => `| ${r.name} | ${(r.wr * 100).toFixed(0)} % | ${r.games} |`),
      "",
    ].join("\n");
    writeFileSync("design/balance-report.md", out);
    process.stdout.write(out + "\n");
  }, 1_800_000);
});
